"""SQLite-backed query store for the active dataset.

SQL entered by users or generated by a language model is untrusted. Rather
than relying on keyword blocklists, queries run on a connection opened with
``mode=ro`` and ``PRAGMA query_only``, so SQLite itself refuses any write.
Results are capped at a row limit and long-running queries are interrupted.
"""

from __future__ import annotations

import contextlib
import logging
import re
import shutil
import sqlite3
import tempfile
import time
import weakref
from dataclasses import dataclass
from pathlib import Path
from types import TracebackType

import pandas as pd

from data_analyst_agent.exceptions import StorageError, UnsafeQueryError

logger = logging.getLogger(__name__)

TABLE_NAME = "dataset"

_LEADING_COMMENTS = re.compile(r"^(\s*(--[^\n]*\n|/\*.*?\*/))*\s*", re.DOTALL)
_READ_ONLY_START = re.compile(r"^(select|with)\b", re.IGNORECASE)
# How many SQLite VM instructions run between timeout checks.
_PROGRESS_INTERVAL = 10_000


@dataclass(frozen=True, slots=True)
class QueryResult:
    frame: pd.DataFrame
    truncated: bool


def quote_identifier(name: str) -> str:
    """Quote a column or table name for SQLite."""
    return '"' + name.replace('"', '""') + '"'


def validate_read_only(sql: str) -> str:
    """Return ``sql`` without trailing semicolons if it is a single SELECT/WITH.

    This check exists to give clear error messages; the read-only connection
    is what actually enforces safety.
    """
    statement = sql.strip().rstrip(";").strip()
    body = _LEADING_COMMENTS.sub("", statement)
    if not body:
        raise UnsafeQueryError("The query is empty.")
    if not _READ_ONLY_START.match(body):
        raise UnsafeQueryError("Only SELECT queries (optionally using WITH) are allowed.")
    return statement


class SQLiteStore:
    """Holds one DataFrame in a temporary SQLite file and answers read-only SQL."""

    def __init__(
        self,
        *,
        row_limit: int = 10_000,
        timeout_seconds: float = 10.0,
    ) -> None:
        self._dir = Path(tempfile.mkdtemp(prefix="data-agent-"))
        self._path = self._dir / "store.sqlite3"
        self.row_limit = row_limit
        self.timeout_seconds = timeout_seconds
        self._finalizer = weakref.finalize(self, shutil.rmtree, self._dir, ignore_errors=True)

    def load(self, df: pd.DataFrame) -> None:
        """Replace the contents of :data:`TABLE_NAME` with ``df``."""
        try:
            with contextlib.closing(sqlite3.connect(self._path)) as conn:
                df.to_sql(TABLE_NAME, conn, if_exists="replace", index=False)
                conn.commit()
        except (sqlite3.Error, ValueError) as exc:
            raise StorageError(f"Could not load data into the query store: {exc}") from exc
        logger.info("Loaded %d rows into table %s", len(df), TABLE_NAME)

    def query(self, sql: str) -> QueryResult:
        statement = validate_read_only(sql)
        deadline = time.monotonic() + self.timeout_seconds

        try:
            with contextlib.closing(self._connect_read_only()) as conn:
                conn.set_progress_handler(
                    lambda: int(time.monotonic() > deadline), _PROGRESS_INTERVAL
                )
                cursor = conn.execute(statement)
                rows = cursor.fetchmany(self.row_limit + 1)
                columns = [d[0] for d in cursor.description or ()]
        except sqlite3.OperationalError as exc:
            if "interrupted" in str(exc):
                raise StorageError(
                    f"Query exceeded the {self.timeout_seconds:g}s time limit."
                ) from exc
            if "readonly" in str(exc) or "read-only" in str(exc):
                raise UnsafeQueryError("The query tried to modify data.") from exc
            raise StorageError(f"SQL error: {exc}") from exc
        except (sqlite3.ProgrammingError, sqlite3.Warning) as exc:
            # Raised for multiple statements in one string.
            raise UnsafeQueryError(f"Invalid query: {exc}") from exc
        except sqlite3.Error as exc:
            raise StorageError(f"SQL error: {exc}") from exc

        truncated = len(rows) > self.row_limit
        frame = pd.DataFrame.from_records(rows[: self.row_limit], columns=columns)
        return QueryResult(frame=frame, truncated=truncated)

    def close(self) -> None:
        self._finalizer()

    def __enter__(self) -> SQLiteStore:
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        self.close()

    def _connect_read_only(self) -> sqlite3.Connection:
        if not self._path.exists():
            raise StorageError("No data has been loaded into the query store yet.")
        conn = sqlite3.connect(f"{self._path.as_uri()}?mode=ro", uri=True)
        conn.execute("PRAGMA query_only = ON")
        return conn
